#!/usr/bin/env python3
"""Generate a checksumed source catalog without self-referential project-book files."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
BOOK = ROOT / "docs" / "project-book"
CATALOG_JSON = BOOK / "source_catalog.json"
CATALOG_MD = BOOK / "SOURCE_CATALOG.md"
SUFFIXES = {".md", ".json", ".go", ".mjs", ".js", ".ts", ".tsx", ".yaml", ".yml", ".py", ".sh", ".mod"}
NON_SOURCE = {".git", ".luna", ".cache", ".venv", "node_modules", "dist", "build", "logs", "reports", "telemetry", "state", "__pycache__"}
PATH_LINK = re.compile(r"\[[^]]+\]\(([^)]+)\)")


def eligible(p: Path) -> bool:
    rel = p.relative_to(ROOT)
    parts = rel.parts
    if any(seg in NON_SOURCE for seg in parts):
        return False
    if len(parts) >= 2 and parts[0] == "docs" and parts[1] == "project-book":
        return False
    return p.name == "go.mod" or (p.suffix.lower() in SUFFIXES and p.is_file())


def classification(path: str) -> str:
    if path.startswith("docs/"):
        if re.match(r"docs/1[4-6]-", path):
            return "historical / handoff"
        if "NETBIRD" in path:
            return "deferred research"
        if "ADRS" in path or "ROADMAP" in path:
            return "decision / roadmap"
        return "architecture / design source"
    if path.startswith("testdata/"):
        return "synthetic test fixture"
    if path.startswith("schemas/"):
        return "API contract (partial semantic)"
    if path.endswith("_test.go"):
        return "unit / negative tests"
    if path.startswith("cmd/"):
        return "executable entry"
    if path.startswith("internal/"):
        return "implementation"
    if path.startswith("scripts/"):
        return "developer tooling"
    return "repository contract"


def load_title(p: Path) -> str:
    if p.suffix != ".md":
        return p.stem
    try:
        with p.open(encoding="utf-8") as f:
            for _ in range(24):
                line = f.readline()
                if not line:
                    break
                if line.startswith("# "):
                    return line[2:].strip()
    except UnicodeError:
        return p.stem
    return p.stem


def source_entries() -> list[dict]:
    entries = []
    for p in sorted(ROOT.rglob("*")):
        if not p.is_file() or not eligible(p):
            continue
        rel = p.relative_to(ROOT).as_posix()
        payload = p.read_bytes()
        entries.append({"path": rel, "category": classification(rel), "title": load_title(p),
                        "bytes": len(payload), "sha256": hashlib.sha256(payload).hexdigest()})
    return entries


def render(entries: list[dict]) -> tuple[str, str]:
    doc = {"schemaVersion": "lightluna.source-catalog.v1",
           "scope": "repository sources excluding docs/project-book and ephemeral artifacts",
           "selfReferentialExcluded": True, "entries": entries}
    raw = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
    lines = [
        "# Light Luna Source Catalog",
        "",
        "Status: generated source index (NOT proof of deployment)",
        "Owner: [project book](README.md); generated by python3 scripts/update_doc_catalog.py",
        "Scope: repository Markdown, source, schema and synthetic fixtures, excluding docs/project-book/.",
        "All SHA-256 values identify exact file bytes in this workspace; uncommitted work can change them.",
        "",
        "| Path | Class | Bytes | SHA-256 |",
        "|---|---|---:|---|",
    ]
    for it in entries:
        path = it["path"]
        lines.append(f"| [{path}](../../{path}) | {it['category']} | {it['bytes']} | {it['sha256']} |")
    lines.extend(["", "Governance files under docs/project-book are intentionally excluded;",
                  "see [Library Map](DOCUMENT_LIBRARY_MAP.md) and [README](README.md).", ""])
    return raw, "\n".join(lines)


def check_links() -> list[str]:
    """Validate relative file links in project-book and root README; skip external URLs."""
    problems = []
    for doc in sorted(BOOK.glob("*.md")) + [ROOT / "README.md"]:
        if not doc.exists():
            continue
        content = doc.read_text(encoding="utf-8")
        for target in PATH_LINK.findall(content):
            target = target.split("#", 1)[0].strip().split(" ", 1)[0]
            if not target or target.startswith(("http://", "https://", "mailto:", "data:", "#")):
                continue
            candidate = (doc.parent / unquote(target)).resolve()
            try:
                candidate.relative_to(ROOT)
            except ValueError:
                problems.append(f"{doc.relative_to(ROOT)} -> outside repo: {target}")
                continue
            if not candidate.exists():
                problems.append(f"{doc.relative_to(ROOT)} -> missing: {target}")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify catalog and do not write")
    ap.add_argument("--check-links", action="store_true", help="validate project-book Markdown links")
    args = ap.parse_args()
    entries = source_entries()
    json_text, md_text = render(entries)
    expected = {CATALOG_JSON: json_text, CATALOG_MD: md_text}
    problems = []
    if args.check:
        for path, content in expected.items():
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                problems.append(f"catalog out of date: {path.relative_to(ROOT)}")
    else:
        BOOK.mkdir(parents=True, exist_ok=True)
        for path, content in expected.items():
            path.write_text(content, encoding="utf-8")
    if args.check_links:
        problems.extend(check_links())
    if problems:
        for problem in problems:
            print("ERROR:", problem, file=sys.stderr)
        return 1
    print(f"{'Verified' if args.check else 'Generated'} {len(entries)} indexed sources; self-reference excluded.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
